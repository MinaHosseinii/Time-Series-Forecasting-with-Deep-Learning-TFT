from lightning.pytorch.callbacks import Callback

class ValidationMetricsCallback(Callback):
    """Custom callback to compute MAE, RMSE, and Bias after each validation epoch."""

    def on_validation_epoch_end(self, trainer, pl_module):
        # Extract predictions and targets from the validation step outputs
        outputs = trainer.callback_metrics  # already logged metrics from model

        # NeuralForecast TFT model stores predictions internally as tensors
        if hasattr(pl_module, 'y_hat') and hasattr(pl_module, 'y'):
            y_pred = pl_module.y_hat.detach().cpu()
            y_true = pl_module.y.detach().cpu()

            mae, bias, rmse = calculate_metrics_torch(y_true, y_pred)

            # Log metrics to Lightning
            trainer.logger.log_metrics({
                'val_MAE': mae,
                'val_Bias': bias,
                'val_RMSE': rmse
            }, step=trainer.global_step)

            print(f"[Validation Metrics] MAE={mae:.4f}, Bias={bias:.4f}, RMSE={rmse:.4f}")
        else:
            print("⚠️ Could not find y_hat/y in pl_module — skipping metric computation.")

