def remove_duplicate_datetimes(df, datetime_col='DateTime'):
    """
    Check for duplicates in a datetime column and remove duplicates while keeping the first occurrence.

    Parameters:
    - df: pd.DataFrame
    - datetime_col: str, name of the datetime column to check for duplicates

    Returns:
    - df_cleaned: pd.DataFrame with duplicates removed
    """
    # Check for duplicates
    duplicates = df[datetime_col].duplicated()
    has_duplicates = duplicates.any()
    print(f"Are there duplicate {datetime_col} entries? {has_duplicates}")

    if has_duplicates:
        print("Duplicated rows (before removal):")
        print(df[df[datetime_col].duplicated(keep=False)])

        # Remove duplicates, keep first
        df_cleaned = df.drop_duplicates(subset=[datetime_col], keep='first')
        print("Duplicates removed, keeping the first occurrence.")
    else:
        df_cleaned = df.copy()
        print("No duplicates found.")

    return df_cleaned

